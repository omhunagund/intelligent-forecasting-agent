def build_overall_forecast_analysis() -> None:
    """Generate overall model/forecast business context."""

    comparison = load_csv(
        "overall_model_comparison"
    )

    ensemble = load_csv(
        "overall_ensemble_predictions"
    )

    lines: list[str] = [
        "# Overall Forecast Analysis",
        "",
        "This document contains project-derived information about "
        "the overall weekly revenue forecasting system.",
        "",
        "It does not contain external industry benchmarks or "
        "unstated business assumptions.",
        "",
        "## Production model decision",
        "",
        "XGBoost is the selected production model for the overall "
        "forecast because it provides consistent TreeSHAP "
        "explanations across all production forecasting levels. "
        "LSTM remains a benchmark in the model comparison.",
        "",
    ]

    if not comparison.empty:

        comparison_view = comparison.copy()

        lines.extend(
            [
                "## Model comparison",
                "",
                dataframe_to_markdown(
                    comparison_view
                ),
                "",
            ]
        )

        best_row = (
            comparison_view.iloc[0]
        )

        lines.extend(
            [
                "### Current ranking",
                "",
                (
                    f"The model ranked first in the stored comparison "
                    f"is **{best_row['model']}**, with mean MAPE "
                    f"of **{format_number(best_row['mean_mape'], 2)}%**."
                ),
                "",
                "The production-model choice is documented separately "
                "from the benchmark ranking so that the agent does not "
                "misrepresent the model-selection decision.",
                "",
            ]
        )

    if not ensemble.empty:

        ensemble["timestamp"] = pd.to_datetime(
            ensemble["timestamp"],
            errors="coerce",
        )

        lines.extend(
            [
                "## Historical ensemble forecast stream",
                "",
                (
                    f"The stored walk-forward ensemble contains "
                    f"**{len(ensemble):,} forecast observations**."
                ),
                "",
                (
                    f"Validation period covered: "
                    f"**{format_date(ensemble['timestamp'].min())}** "
                    f"to "
                    f"**{format_date(ensemble['timestamp'].max())}**."
                ),
                "",
            ]
        )

    lines.extend(
        [
            source_note(
                [
                    "overall_model_comparison",
                    "overall_ensemble_predictions",
                ]
            ),
            "",
        ]
    )

    write_markdown(
        BUSINESS_CONTEXT_DIR
        / "overall_forecast_analysis.md",
        "\n".join(lines),
    )


