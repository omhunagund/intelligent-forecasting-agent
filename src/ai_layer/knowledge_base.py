# 7. HISTORICAL FORECAST OUTCOMES
# ============================================================================

def build_historical_forecast_outcomes() -> None:
    """
    Create a compact historical forecasting document.

    This records actual vs predicted values from the validated
    walk-forward ensemble output. It does not claim that future
    outcomes are known.
    """

    ensemble = load_csv(
        "overall_ensemble_predictions"
    )

    if ensemble.empty:
        raise ValueError(
            "Overall ensemble prediction report is empty."
        )

    ensemble["timestamp"] = pd.to_datetime(
        ensemble["timestamp"],
        errors="coerce",
    )

    actual = pd.to_numeric(
        ensemble["actual"],
        errors="coerce",
    )

    predicted = pd.to_numeric(
        ensemble["predicted"],
        errors="coerce",
    )

    absolute_error = (
        actual
        - predicted
    ).abs()

    outcome_df = pd.DataFrame(
        {
            "fold":
                ensemble.get(
                    "fold",
                    pd.Series(
                        dtype="float64"
                    ),
                ),
            "timestamp":
                ensemble["timestamp"],
            "actual_revenue":
                actual,
            "forecast_revenue":
                predicted,
            "absolute_error":
                absolute_error,
        }
    )

    lines: list[str] = [
        "# Historical Forecast Outcomes",
        "",
        "This document summarizes realized outcomes from the "
        "project's historical walk-forward ensemble forecasts.",
        "",
        "Each record represents a forecast that was evaluated "
        "against a subsequently observed actual value within the "
        "historical validation period.",
        "",
        "These records should be used for historical comparison, "
        "not as evidence that future actuals are already known.",
        "",
        "## Historical forecast outcomes",
        "",
        dataframe_to_markdown(
            outcome_df.sort_values(
                "timestamp"
            ),
            max_rows=500,
        ),
        "",
        source_note(
            [
                "overall_ensemble_predictions",
            ]
        ),
        "",
    ]

    write_markdown(
        FORECAST_HISTORY_DIR
        / "historical_forecast_outcomes.md",
        "\n".join(lines),
    )


