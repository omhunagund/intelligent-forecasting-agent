def ensure_directories() -> None:
    """Create the knowledge-base output directories."""

    BUSINESS_CONTEXT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    FORECAST_HISTORY_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )


def source_exists(
    source_key: str,
) -> bool:
    """Return whether a configured source artifact exists."""

    path = SOURCE_FILES[source_key]

    return path.is_file()


def load_csv(
    source_key: str,
) -> pd.DataFrame:
    """
    Load a CSV source.

    Missing files are handled explicitly so the generated document
    can report missing upstream artifacts instead of inventing data.
    """

    path = SOURCE_FILES[source_key]

    if not path.is_file():
        raise FileNotFoundError(
            f"Required source file not found:\n{path}"
        )

    return pd.read_csv(
        path
    )


def load_parquet(
    source_key: str,
) -> pd.DataFrame:
    """Load a Parquet source."""

    path = SOURCE_FILES[source_key]

    if not path.is_file():
        raise FileNotFoundError(
            f"Required source file not found:\n{path}"
        )

    return pd.read_parquet(
        path
    )


def load_json(
    source_key: str,
) -> dict[str, Any]:
    """Load a JSON source."""

    path = SOURCE_FILES[source_key]

    if not path.is_file():
        raise FileNotFoundError(
            f"Required source file not found:\n{path}"
        )

    with open(
        path,
        "r",
        encoding="utf-8",
    ) as file:
        return json.load(file)


def write_markdown(
    path: Path,
    content: str,
) -> None:
    """Write one Markdown knowledge document."""

    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    path.write_text(
        content,
        encoding="utf-8",
    )


def format_number(
    value: Any,
    decimals: int = 2,
) -> str:
    """Format numeric values safely for Markdown."""

    if pd.isna(value):
        return "N/A"

    try:
        return f"{float(value):,.{decimals}f}"

    except (
        TypeError,
        ValueError,
    ):
        return str(value)


def format_date(
    value: Any,
) -> str:
    """Format a date-like value safely."""

    if pd.isna(value):
        return "N/A"

    try:
        return pd.Timestamp(
            value
        ).strftime(
            "%Y-%m-%d"
        )

    except (
        TypeError,
        ValueError,
    ):
        return str(value)


def dataframe_to_markdown(
    df: pd.DataFrame,
    columns: list[str] | None = None,
    max_rows: int | None = None,
) -> str:
    """
    Convert a dataframe to Markdown without depending on optional
    display formatting.
    """

    data = df.copy()

    if columns is not None:
        existing = [
            column
            for column in columns
            if column in data.columns
        ]

        data = data[
            existing
        ]

    if max_rows is not None:
        data = data.head(
            max_rows
        )

    if data.empty:
        return (
            "_No records available._"
        )

    return data.to_markdown(
        index=False
    )


def source_note(
    source_keys: list[str],
) -> str:
    """Create a transparent source section."""

    lines = [
        "## Source artifacts",
        "",
    ]

    for key in source_keys:

        path = SOURCE_FILES[key]

        lines.append(
            f"- `{path.relative_to(PROJECT_ROOT)}`"
        )

    return "\n".join(
        lines
    )


