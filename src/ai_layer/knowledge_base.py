def validate_generated_knowledge_base() -> None:
    """Validate that the expected Stage-1 knowledge documents exist."""

    expected_files = [
        BUSINESS_CONTEXT_DIR
        / "overall_forecast_analysis.md",

        BUSINESS_CONTEXT_DIR
        / "category_forecast_analysis.md",

        BUSINESS_CONTEXT_DIR
        / "regional_forecast_analysis.md",

        BUSINESS_CONTEXT_DIR
        / "explainability_context.md",

        BUSINESS_CONTEXT_DIR
        / "monitoring_context.md",

        BUSINESS_CONTEXT_DIR
        / "data_quality_context.md",

        FORECAST_HISTORY_DIR
        / "historical_forecast_outcomes.md",
    ]

    missing = [
        path
        for path in expected_files
        if not path.is_file()
    ]

    if missing:
        raise RuntimeError(
            "Knowledge-base generation failed. "
            f"Missing files: {missing}"
        )

    empty = [
        path
        for path in expected_files
        if path.stat().st_size == 0
    ]

    if empty:
        raise RuntimeError(
            "Knowledge-base generation produced empty files: "
            f"{empty}"
        )


